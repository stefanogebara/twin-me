import crypto from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
const API = 'http://127.0.0.1:3007';
const EMAIL = 'stefanogebara@gmail.com';
const sb = createClient(process.env.VITE_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
const raw = crypto.randomBytes(32).toString('hex');
await sb.from('magic_link_tokens').insert({ token_hash: crypto.createHash('sha256').update(raw).digest('hex'), email: EMAIL, expires_at: new Date(Date.now() + 600000).toISOString() });
const r = await fetch(`${API}/api/auth/magic-link/verify?token=${raw}`, { redirect: 'manual' });
const cookie = (r.headers.get('set-cookie') || '').split(';')[0];
const rf = await fetch(`${API}/api/auth/refresh`, { method: 'POST', headers: { cookie } });
const { accessToken } = await rf.json();
const H = { authorization: `Bearer ${accessToken}`, 'content-type': 'application/json' };
const before = await (await fetch(`${API}/api/money/chat/history`, { headers: H })).json();
const q = 'How much on groceries this month?';
const said = await (await fetch(`${API}/api/money/chat`, { method: 'POST', headers: H, body: JSON.stringify({ message: q, history: [] }) })).json();
console.log('asked   :', q);
console.log('answer  :', (said.data?.text || '').slice(0, 110));
console.log('next now:', JSON.stringify(said.data?.next || []));
const after = await (await fetch(`${API}/api/money/chat/history`, { headers: H })).json();
const kept = (after.data || []).filter((t) => t.role === 'twin').slice(-1)[0];
console.log('kept    :', (kept?.text || '').slice(0, 60));
console.log('next kept:', JSON.stringify(kept?.next || []));
console.log('turns    :', (before.data || []).length, '->', (after.data || []).length);
process.exit(0);
