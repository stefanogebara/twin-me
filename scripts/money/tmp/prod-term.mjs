import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';
import crypto from 'node:crypto';
const API = 'https://twin-ai-learn.vercel.app';
const sb = createClient(process.env.VITE_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
const raw = crypto.randomBytes(32).toString('hex');
await sb.from('magic_link_tokens').insert({ token_hash: crypto.createHash('sha256').update(raw).digest('hex'), email: 'stefanogebara@gmail.com', expires_at: new Date(Date.now() + 600000).toISOString() });
const r = await fetch(`${API}/api/auth/magic-link/verify?token=${raw}`, { redirect: 'manual' });
const cookie = (r.headers.get('set-cookie') || '').split(';')[0];
const { accessToken } = await (await fetch(`${API}/api/auth/refresh`, { method: 'POST', headers: { cookie } })).json();
const res = await fetch(`${API}/api/money/plan`, { headers: { Authorization: `Bearer ${accessToken}` } });
const body = await res.json();
const term = body?.data?.term;
console.log('status', res.status, '| month', body?.data?.month);
console.log('term:', term ? term.weeks.map((w) => `${w.start}${w.current ? '*' : ''}=${w.known ? w.events : '--'}`).join(' ') : JSON.stringify(term));
const cells = body?.data?.cells || [];
console.log('cells with an event count > 0:', cells.filter((c) => (c.events || 0) > 0).length, 'of', cells.length);
console.log('calendar items on coming days:', cells.flatMap((c) => c.items || []).filter((i) => i.kind === 'calendar').map((i) => `${i.label} ${i.amount}`).join(', ') || 'none');
process.exit(0);
